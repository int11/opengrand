#!/usr/bin/env python3
"""Generate firmware C tables and app TypeScript tables from spec/ca79.json.

  python3 -I result/protocol/tools/gen.py

Outputs (checked in, never edited by hand):
  firmware/include/ca79ng/params_gen.h
  firmware/src/kproto/params_gen.c
  app/src/protocol/params.gen.ts
  firmware/include/ca79ng/ngver_gen.h, app/src/protocol/ngver.gen.ts, protocol/NGVER.md
    (OpenGrand protocol version, spec ng_versions)
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RESULT = os.path.abspath(os.path.join(HERE, "..", ".."))
SPEC = os.path.join(HERE, "..", "spec", "ca79.json")

FN_SUFFIX = {0x10: "", 0x31: "_MODE", 0x32: "_REMOTE"}

# Parameter storage slots in the firmware (part byte -> slot). MIDI channel n
# uses part byte 0x2F + n (MIDI2ch = 49, observed in protocol_spec "Sound").
SLOTS = [("Main1", 0x00), ("Layer", 0x08), ("Lower", 0x09), ("FourHandsRight", 0x0A),
         ("FourHandsLeft", 0x0B), ("Global", 0x0F), ("System", 0x7F)] + \
        [(f"MIDI{n}ch", 0x2F + n) for n in range(1, 17)]
SLOT_INDEX = {name: i for i, (name, _) in enumerate(SLOTS)}


def c_ident(name):
    s = re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_")
    s = re.sub(r"([a-z])([A-Z])", r"\1_\2", s).upper()
    return s


def unique_names(params):
    used = {}
    out = []
    for p in params:
        base = c_ident(p["name"]) + FN_SUFFIX.get(p["fn"], f"_{p['fn']:02X}")
        n = base
        k = 2
        while n in used:
            n = f"{base}_{k}"
            k += 1
        used[n] = True
        out.append(n)
    return out


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_c(spec, idents):
    params = spec["params"]
    h = ["/* Generated by protocol/tools/gen.py from protocol/spec/ca79.json — do not edit. */",
         "#ifndef CA79NG_PARAMS_GEN_H", "#define CA79NG_PARAMS_GEN_H", "", "#include <stdint.h>", "",
         "typedef enum {"]
    for i, ident in enumerate(idents):
        p = params[i]
        h.append(f"    PRM_{ident} = {i}, /* fn {p['fn']:02X} {p['v1']:02X} {p['v2']:02X} len {p['len']} */")
    h += [f"    PRM_COUNT = {len(params)}", "} param_id_t;", "",
          f"#define PARAM_SLOT_COUNT {len(SLOTS)}", "typedef enum {"]
    for i, (name, v3) in enumerate(SLOTS):
        h.append(f"    SLOT_{c_ident(name)} = {i}, /* part byte 0x{v3:02X} */")
    h += ["} param_slot_t;", "",
          "/* scope of a parameter (firmware descriptor part rule) */",
          "enum { SCOPE_PART = 0, SCOPE_GLOBAL = 1, SCOPE_SYSTEM = 2, SCOPE_RECORDER = 3 };",
          "/* value codec classes for range parameters */",
          "enum { CODEC_RAW = 0, CODEC_RANGE = 1, CODEC_ENUM = 2, CODEC_BOOL = 3 };", "",
          "typedef struct {",
          "    const char *name;",
          "    uint8_t fn, v1, v2;",
          "    uint8_t scope;",
          "    uint8_t len;        /* data bytes (0..6) */",
          "    uint8_t var_len;    /* variable-length / streamed payload: not stored */",
          "    uint8_t codec;",
          "    uint8_t data_max[4];",
          "    uint8_t ui_min, ui_max, raw_min, raw_max; /* CODEC_RANGE */",
          "} param_desc_t;", "",
          "typedef struct { uint8_t param, slot, len, data[4]; } param_default_t;",
          "/* msb/lsb/pc = the Sound (55 00) wire triple; prog = 0-based position in the manual program change list */",
          "typedef struct { const char *name; const char *category; uint8_t msb, lsb, pc, prog; } sound_desc_t;",
          "typedef struct { const char *name; const char *category; uint8_t numerator, denominator; } rhythm_desc_t;", "",
          "extern const param_desc_t PARAM_DESC[PRM_COUNT];",
          "extern const uint8_t PARAM_SLOT_PART[PARAM_SLOT_COUNT];",
          "extern const param_default_t PARAM_DEFAULTS[];",
          "extern const unsigned PARAM_DEFAULT_COUNT;",
          "extern const sound_desc_t SOUND_TABLE[];",
          "extern const unsigned SOUND_COUNT;",
          "extern const rhythm_desc_t RHYTHM_TABLE[];",
          "extern const unsigned RHYTHM_COUNT_GEN;", "", "#endif", ""]

    scope_map = {"part": "SCOPE_PART", "global": "SCOPE_GLOBAL", "system": "SCOPE_SYSTEM", "recorder": "SCOPE_RECORDER"}
    c = ["/* Generated by protocol/tools/gen.py from protocol/spec/ca79.json — do not edit. */",
         '#include "ca79ng/params_gen.h"', "", "const param_desc_t PARAM_DESC[PRM_COUNT] = {"]
    for i, p in enumerate(params):
        codec = p.get("codec", {})
        cls = codec.get("class", "")
        if cls.startswith("F(range)") and "raw_min" in codec:
            kind = "CODEC_RANGE"
            rng = (int(codec["ui_min"]), int(codec["ui_max"]), int(codec["raw_min"]), int(codec["raw_max"]))
        else:
            kind = {"enum": "CODEC_ENUM", "boolean": "CODEC_BOOL"}.get(p["kind"], "CODEC_RAW")
            rng = (0, 0, 0, 0)
        dm = (p["data_max"] + [0, 0, 0, 0])[:4]
        rng_c = ", ".join(str(v & 0xFF) for v in rng)
        c.append(f"    [PRM_{idents[i]}] = {{{c_str(p['name'])}, 0x{p['fn']:02X}, 0x{p['v1']:02X}, 0x{p['v2']:02X}, "
                 f"{scope_map[p['scope']]}, {p['len']}, {int(p['var_len'])}, {kind}, "
                 f"{{{', '.join(str(x) for x in dm)}}}, {rng_c}}},")
    c += ["};", "", "const uint8_t PARAM_SLOT_PART[PARAM_SLOT_COUNT] = {" +
          ", ".join(f"0x{v3:02X}" for _, v3 in SLOTS) + "};", "", "const param_default_t PARAM_DEFAULTS[] = {"]
    ndef = 0
    for i, p in enumerate(params):
        if p["var_len"]:
            continue
        for d in p.get("default", []):
            raw = d.get("raw_data")
            slot = SLOT_INDEX.get(d.get("part"))
            if raw is None or slot is None or len(raw) != p["len"] or p["len"] > 4:
                continue
            if any((not isinstance(b, int)) or b < 0 or b > 127 for b in raw):
                continue
            c.append(f"    {{PRM_{idents[i]}, {slot}, {len(raw)}, {{{', '.join(str(b) for b in raw)}}}}}, /* {d['part']} */")
            ndef += 1
    c += ["};", f"const unsigned PARAM_DEFAULT_COUNT = {ndef};", "", "const sound_desc_t SOUND_TABLE[] = {"]
    for s in spec["sounds"]:
        c.append(f"    {{{c_str(s['name'])}, {c_str(s['category'])}, {s['msb']}, {s['lsb']}, {s['pc']}, {s['prog']}}},")
    c += ["};", f"const unsigned SOUND_COUNT = {len(spec['sounds'])};", "", "const rhythm_desc_t RHYTHM_TABLE[] = {"]
    for r in spec["rhythms"]:
        num, den = (r["beat"].split("/") + ["4"])[:2]
        c.append(f"    {{{c_str(r['name'])}, {c_str(r['category'])}, {int(num)}, {int(den)}}},")
    c += ["};", f"const unsigned RHYTHM_COUNT_GEN = {len(spec['rhythms'])};", ""]
    return "\n".join(h), "\n".join(c), ndef


def gen_ts(spec, idents):
    out = ["// Generated by protocol/tools/gen.py from protocol/spec/ca79.json — do not edit.", "",
           "export interface EnumValue { raw: number; sub: number | null; label: string }",
           "export interface RangeCodec { uiMin: number; uiMax: number; rawMin: number; rawMax: number; encodeTable?: Record<string, number> }",
           "export interface ParamDef {",
           "  id: string; name: string; fn: number; v1: number; v2: number;",
           "  scope: \"part\" | \"global\" | \"system\" | \"recorder\";",
           "  len: number; varLen: boolean; kind: string; dataMax: number[];",
           "  values?: EnumValue[]; range?: RangeCodec; unit?: string; codecClass?: string;",
           "  parts?: Record<string, number>;",
           "}", "", "export const PARAMS: ParamDef[] = ["]
    for i, p in enumerate(spec["params"]):
        d = {"id": idents[i], "name": p["name"], "fn": p["fn"], "v1": p["v1"], "v2": p["v2"], "scope": p["scope"],
             "len": p["len"], "varLen": p["var_len"], "kind": p["kind"], "dataMax": p["data_max"]}
        if p.get("values"):
            d["values"] = p["values"]
        codec = p.get("codec", {})
        if codec.get("class", "").startswith("F(range)") and "raw_min" in codec:
            d["range"] = {"uiMin": codec["ui_min"], "uiMax": codec["ui_max"], "rawMin": codec["raw_min"],
                          "rawMax": codec["raw_max"]}
            if codec.get("encode_table"):
                d["range"]["encodeTable"] = codec["encode_table"]
        if codec.get("class"):
            d["codecClass"] = codec["class"]
        if p.get("unit"):
            d["unit"] = p["unit"]
        if p.get("parts"):
            d["parts"] = p["parts"]
        out.append("  " + json.dumps(d, ensure_ascii=False) + ",")
    out += ["];", "",
            "export const PART_V3: Record<string, number> = " + json.dumps({n: v for n, v in SLOTS}) + ";", "",
            "/** msb/lsb/pc = the Sound (55 00) wire triple; prog = 0-based position in the manual program change list;",
            " * defaults = Main1 values the stock app sends with the sound (display value or value label, stock order) */",
            "export interface SoundDef { name: string; category: string; msb: number; lsb: number; pc: number; prog: number; defaults: [string, string | number][]; vt: string[] }",
            "export const SOUNDS: SoundDef[] = " + json.dumps(spec["sounds"], ensure_ascii=False) + ";", "",
            "export interface RhythmDef { index: number; name: string; category: string; beat: string }",
            "export const RHYTHMS: RhythmDef[] = " + json.dumps(spec["rhythms"], ensure_ascii=False) + ";", "",
            "export const VT_PRESETS: Record<string, unknown>[] = " + json.dumps(spec["vt_presets"], ensure_ascii=False) + ";", "",
            "export const MODEL = " + json.dumps(spec["model"]) + " as const;", ""]
    return "\n".join(out)


def gen_md(spec, idents):
    scope = {"part": "part", "global": "0x7F", "system": "0x0F", "recorder": "recorder"}
    out = ["# CA79 parameter reference (generated)", "",
           "Generated by `result/protocol/tools/gen.py` from `result/protocol/spec/ca79.json`.",
           "Wire: `F0 40 <dev> <fn> 08 02 <v1> <v2> <part> <data…> F7` (controller → piano); the piano answers with `04 1E` in bytes 4–5.",
           "`data max` comes from the original firmware descriptor table (0x400faa2c); value labels / codecs from the original app.", "",
           "| # | Name | fn | v1 v2 | part | len | data max | codec / values | default (part: raw) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for i, p in enumerate(spec["params"]):
        c = p.get("codec", {})
        if c.get("class", "").startswith("F(range)") and "raw_min" in c:
            codec = f"range {c['ui_min']}..{c['ui_max']} ↔ {c['raw_min']}..{c['raw_max']}"
        elif p.get("values"):
            vals = ", ".join(f"{v['raw']}{'/' + str(v['sub']) if v['sub'] is not None else ''}={v['label']}" for v in p["values"][:8])
            codec = vals + (" …" if len(p["values"]) > 8 else "")
        else:
            codec = c.get("layout") or p["kind"]
        d = "; ".join(f"{x['part']}: {' '.join(str(b) for b in x['raw_data'])}" for x in p.get("default", [])[:3]
                      if x.get("raw_data") is not None)
        name = p["name"] + (" *(var)*" if p["var_len"] else "")
        out.append(f"| {i} | {name} | {p['fn']:02X} | {p['v1']:02X} {p['v2']:02X} | {scope[p['scope']]} | {p['len']} | "
                   f"{' '.join(str(x) for x in p['data_max'])} | {codec.replace('|', '/')} | {d} |")
    return "\n".join(out) + "\n"


def gen_ngver_h(ng):
    fz = ng["frozen"]
    out = ["/* Generated by protocol/tools/gen.py from protocol/spec/ca79.json (ng_versions) — do not edit.",
           " * OpenGrand protocol version: Identify byte 1 (ngver), REMOTE_PROTOCOL.md section 10.0, NGVER.md. */",
           "#ifndef CA79NG_NGVER_GEN_H", "#define CA79NG_NGVER_GEN_H", "",
           f"#define NG_PROTO_VERSION {ng['current']}   /* what ota_main built from this tree reports */",
           "/* the four feature bytes every image with ngver >= 2 reports, unchanged from version to version */"]
    out += [f"#define NG_FEAT{i}_FROZEN 0x{b:02X}" for i, b in enumerate(fz)]
    out += ["", "/* version that implies each feature (0 = none: the bit alone) */"]
    for f in ng["features"]:
        out.append(f"#define NG_SINCE_{f['name'].upper()} {f['since'] or 0}")
    out += ["", "#endif", ""]
    return "\n".join(out)


def gen_ngver_ts(ng):
    feats = [{"name": f["name"], "byte": f["byte"], "bit": f["bit"], "since": f["since"]} for f in ng["features"]]
    out = ["// Generated by protocol/tools/gen.py from protocol/spec/ca79.json (ng_versions) — do not edit.",
           "// OpenGrand protocol version: Identify byte 1 (ngver), REMOTE_PROTOCOL.md section 10.0, protocol/NGVER.md.", "",
           "/** what ota_main built from this tree reports in Identify byte 1 */",
           f"export const NG_PROTO_VERSION = {ng['current']};",
           "/** the four feature bytes every image with ngver >= 2 reports, unchanged from version to version */",
           "export const NG_FEAT_FROZEN: readonly number[] = " + json.dumps(ng["frozen"]) + ";", "",
           "/** byte/bit: Identify feature byte (0-3) and bit, null = no bit; since: version that implies it, null = none */",
           "export interface NgFeatureDef { name: string; byte: number | null; bit: number | null; since: number | null }",
           "export const NG_FEATURE_TABLE: readonly NgFeatureDef[] = ["]
    out += ["  " + json.dumps(f) + "," for f in feats]
    out += ["];", "",
            "export type NgFeatureName = " + " | ".join(json.dumps(f["name"]) for f in feats) + ";", "",
            "const BY_NAME = new Map(NG_FEATURE_TABLE.map((f) => [f.name, f]));", "",
            "/** The one feature rule: present when ngver >= since, or when the feature has a bit and that bit is set in",
            " * feats[byte] (feats = Identify feature bytes feat0..feat3, missing = 0). */",
            "export function ngFeature(ngver: number, feats: readonly (number | undefined)[], name: NgFeatureName): boolean {",
            "  const f = BY_NAME.get(name);",
            "  if (!f) return false;",
            "  if (f.since != null && ngver >= f.since) return true;",
            "  return f.byte != null && f.bit != null && ((feats[f.byte] ?? 0) & f.bit) !== 0;",
            "}", ""]
    return "\n".join(out)


def gen_ngver_md(ng):
    out = ["# OpenGrand protocol versions (generated)", "",
           "Generated by `result/protocol/tools/gen.py` from `spec/ca79.json` `ng_versions` (edit the table "
           "there) — do not edit. Contract: [REMOTE_PROTOCOL §10.0](REMOTE_PROTOCOL.md#100-프로토콜-판-ngver).", "",
           f"Current version (what `ota_main` built from this tree reports in Identify byte 1): **{ng['current']}**. "
           "From version 2 the four feature bytes are frozen at "
           + " / ".join(f"`0x{b:02X}`" for b in ng["frozen"]) + " (feat0 / feat1 / feat2 / feat3).", "",
           "Rule: a feature is present when `ngver >= since`, or when it has a bit and that bit is set. "
           "`since` — = never implied by a version (diagnostic / demo images only).", "",
           "| ngver | images |", "|---|---|"]
    out += [f"| {v['ver']} | {v['what']} |" for v in ng["versions"]]
    out += ["", "| feature | byte | bit | since | what |", "|---|---|---|---|---|"]
    for f in ng["features"]:
        byte = "—" if f["byte"] is None else f"feat{f['byte']}"
        bit = "—" if f["bit"] is None else f"`0x{f['bit']:02X}`"
        out.append(f"| `{f['name']}` | {byte} | {bit} | {f['since'] or '—'} | {f['what']} |")
    return "\n".join(out) + "\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, RESULT))


def main():
    with open(SPEC, encoding="utf-8") as f:
        spec = json.load(f)
    idents = unique_names(spec["params"])
    h, c, ndef = gen_c(spec, idents)
    write(os.path.join(RESULT, "firmware", "include", "ca79ng", "params_gen.h"), h)
    write(os.path.join(RESULT, "firmware", "src", "kproto", "params_gen.c"), c)
    write(os.path.join(RESULT, "app", "src", "protocol", "params.gen.ts"), gen_ts(spec, idents))
    write(os.path.join(RESULT, "protocol", "PARAMS.md"), gen_md(spec, idents))
    ng = spec["ng_versions"]
    write(os.path.join(RESULT, "firmware", "include", "ca79ng", "ngver_gen.h"), gen_ngver_h(ng))
    write(os.path.join(RESULT, "app", "src", "protocol", "ngver.gen.ts"), gen_ngver_ts(ng))
    write(os.path.join(RESULT, "protocol", "NGVER.md"), gen_ngver_md(ng))
    print(f"{len(spec['params'])} params, {ndef} defaults, {len(spec['sounds'])} sounds, {len(spec['rhythms'])} rhythms")


if __name__ == "__main__":
    main()
